function apply(rel, pairs) {
  const path = join(process.cwd(), rel);
  let text = readFileSync(path, "utf8");
  const misses = [];
  for (const [from, to] of pairs) {
    if (!text.includes(from)) {
      misses.push(from.slice(0, 60));
      continue;
    }
    text = text.split(from).join(to);
  }
  writeFileSync(path, text, "utf8");
  const left = (text.match(/[\u2013\u2014]/g) || []).length;
  console.log(`${rel}: пар ${pairs.length}, не нашлось ${misses.length}, тире осталось ${left}`);
  if (misses.length) console.log(misses.map((m) => `  нет: ${m}`).join("\n"));
}

// Мертвый дубль опубликованного: массив базовых постов и его хелпер.
function stripBase() {
  const path = join(process.cwd(), "src/channel/posts.ts");
  let text = readFileSync(path, "utf8");

  const from = text.indexOf("function post(");
  const to = text.indexOf("/**\n * Автопост:");
  if (from < 0 || to < 0 || to < from) throw new Error("posts.ts: границы базовых постов не найдены");
  text = text.slice(0, from) + text.slice(to);

  text = text.replace(
    /\/\*\* Опубликованные базовые посты[^\n]*\n?export const CHANNEL_POSTS_PUBLISHED_BASE[^\n]*\n\n?/,
    ""
  );

  writeFileSync(path, text, "utf8");
  console.log("posts.ts: базовые 13 постов и хелпер post() удалены");
}

