  function slug(e) {
    return String(e.name || "")
      .toLowerCase()
      .replace(/ё/g, "е")
      .replace(/[-–—]/g, " ")
      .replace(/\s+/g, " ")
      .trim()
      .split("")
      .map(function (ch) {
        return TRANSLIT[ch] != null ? TRANSLIT[ch] : ch;
      })
      .join("")
      .replace(/[^a-z0-9]+/g, "-")
      .replace(/^-+|-+$/g, "");
  }

