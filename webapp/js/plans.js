  /*
   * Схема подходов под цель.
   *
   * Движения для набора и для снижения веса одни и те же, отличается дозировка.
   * На массе выше объём: лишний подход и верх диапазона повторов. На дефиците
   * объём не наращивают — восстановление хуже, а задача силовой другая: удержать
   * мышцы и силу, поэтому вес на снаряде держим, а не снижаем.
   */
  function scheme(e, goal) {
    var d = dose(e);
    var sets = d.sets + (goal === "bulk" ? 1 : 0);
    var setsText = sets + " " + plural(sets, "подход", "подхода", "подходов");

    if (d.secs) {
      var lo = d.secs[0];
      var hi = d.secs[1];
      if (goal === "bulk") {
        lo = Math.round((lo * 1.5) / 5) * 5;
        hi = Math.round((hi * 1.5) / 5) * 5;
      }
      return setsText + " × " + lo + "–" + hi + " " + plural(hi, "секунда", "секунды", "секунд");
    }

    var reps = d.reps || 10;
    var repsText = goal === "bulk" ? reps + "–" + (reps + 2) : String(reps);
    var unit = d.unit || plural(reps, "раз", "раза", "раз");
    return setsText + " × " + repsText + " " + unit + (d.tail ? " " + d.tail : "");
  }

