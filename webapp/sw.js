// Пустой service worker: нужен только для того, чтобы браузер считал
// приложение «устанавливаемым» (добавление на главный экран как PWA).
// Ничего не кэширует и не встаёт между приложением и сервером намеренно —
// в приложении уже есть отдельная проверка версии (полоса «Открыта старая
// версия»), и кэш service worker'а только мешал бы ей, показывая старый код
// вместо свежего.

self.addEventListener("install", () => {
  self.skipWaiting();
});

self.addEventListener("activate", (event) => {
  event.waitUntil(self.clients.claim());
});

self.addEventListener("fetch", () => {
  // Намеренно ничего не делаем: браузер сам идёт в сеть, как без service worker'а.
});
